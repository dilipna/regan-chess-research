"""EXPERIMENTAL AIF-format export.

Experimental AIF-compatible export. Compatibility with Professor Regan's current IR analyzer has not
been tested.

Based only on the publicly documented AIF v0.5 description (K. Regan & T. Biswas, presented in
"A Computer Chess Analysis Interchange Format", Godel's Lost Letter and P=NP, 2015-01-20):
an AIF game is a legal PGN game with extra tags followed by move blocks; each move block has the
tags GID, EID, Turn, MovePlayed, EngineMove, Eval, Depth, NodeCount, FEN, RepCount,
NumLegalMoves, LegalMoves, then an evaluation grid (rows = moves, columns = depths) and the
principal variation. Grid cells: centipawns ("+132", "-053"), "n.a." (not available at that
depth), "NREC" (not recorded), "PRUN" (beyond the MultiPV cap). Evaluations lie in [-900, +900];
1000-n denotes mate-in-n.

Faithfulness rules (nothing is fabricated):
  * ChessAssistLens records only the FINAL-depth MultiPV values, so all shallower depth columns
    are "n.a.".
  * Legal moves outside the recorded MultiPV lines are listed as "PRUN" rows only for the played
    move (the played move's value estimated from the next position is NOT written to the grid).
  * NodeCount was not recorded and is written as "n.a.".
  * Positions analysed only by the depth-8 single-PV prefilter carry Depth "8" and MultiPV 1.
"""

from __future__ import annotations

import platform

import chess

from .. import config

LABEL = ("Experimental AIF-compatible export. Compatibility with Professor Regan's current IR analyzer "
         "has not been tested.")


def _cell(cp: float | None) -> str:
    if cp is None:
        return "n.a."
    cp = float(cp)
    if abs(cp) >= config.MATE_CP - 500:            # python-chess mate_score - n
        n = int(config.MATE_CP - abs(cp))
        v = 1000 - n
        return f"{'+' if cp > 0 else '-'}{v:03d}"
    v = int(round(max(-900, min(900, cp))))
    return f"{'+' if v >= 0 else '-'}{abs(v):03d}"


def _pv_san(fen: str, pv: list[str]) -> str:
    b = chess.Board(fen)
    parts = []
    for i, u in enumerate(pv):
        m = chess.Move.from_uci(u)
        if m not in b.legal_moves:
            break
        if b.turn == chess.WHITE:
            parts.append(f"{b.fullmove_number}.{b.san(m)}")
        elif i == 0:
            parts.append(f"{b.fullmove_number}...{b.san(m)}")
        else:
            parts.append(b.san(m))
        b.push(m)
    return " ".join(parts)


def _wrap(items: list[str], width: int = 90) -> str:
    lines, cur = [], ""
    for it in items:
        add = (it if not cur else "," + it)
        if len(cur) + len(add) > width:
            lines.append(cur + ",")
            cur = it
        else:
            cur += add
    lines.append(cur)
    return "\n".join(lines)


def report_to_aif(report: dict, color: str | None = None) -> str:
    g = report["game"]
    analysis = report.get("analysis", {})
    depth = int(analysis.get("depth", config.SF_DEPTH))
    multipv = int(analysis.get("multipv", config.SF_MULTIPV))
    engine = analysis.get("engine", "Stockfish").replace(" ", "-")
    synthetic = report.get("synthetic")
    game_id = ";".join([g["white"], g["black"], "?", "?", "?", "?", g.get("result", "*")])
    colors = [color] if color in ("white", "black") else ["white", "black"]

    rows = []
    for c in colors:
        p = report["players"].get(c)
        if p:
            rows += p["timeline"]
    rows.sort(key=lambda r: r["ply"])
    first_turn = f"{rows[0]['move_no']}-{rows[0]['color'][0]}" if rows else "1-w"

    out = [f"; {LABEL}",
           "; Generated by ChessAssistLens from its internal JSON analysis (internal storage is not AIF).",
           "; Only final-depth MultiPV values were recorded; shallower depth columns are n.a."]
    if synthetic:
        out.append(f"; WARNING: SYNTHETIC VARIANT ({synthetic['strategy']}, {synthetic['level']:.0%}) - "
                   "MovePlayed at substituted turns is an engine-inserted move, not a human move.")
    out += [
        f'[Event "?"]', f'[Site "?"]', f'[Date "????.??.??"]', f'[Round "?"]',
        f'[White "{g["white"]}"]', f'[Black "{g["black"]}"]', f'[Result "{g.get("result", "*")}"]',
        f'[WhiteElo "{g.get("white_elo") or "?"}"]', f'[BlackElo "{g.get("black_elo") or "?"}"]',
        f'[GameID "{game_id}"]', f'[EngineID "{engine}"]',
        f'[Platform "{platform.system()} {platform.release()} {platform.architecture()[0]}"]',
        f'[Threads "1"]', f'[Hash "{config.SF_HASH_MB}"]', f'[MultiPV "{multipv}"]',
        f'[DepthRange "{depth}-{depth}"]', f'[EGT "none"]', f'[Mode "forward;r;{first_turn}"]', "",
    ]
    # PGN movetext of the original game
    b = chess.Board(g["start_fen"])
    toks = []
    for mv in g["moves"]:
        m = chess.Move.from_uci(mv["uci"])
        if b.turn == chess.WHITE:
            toks.append(f"{b.fullmove_number}.")
        toks.append(b.san(m))
        b.push(m)
    toks.append(g.get("result", "*"))
    out += [_wrap(toks, 80).replace(",", " "), ""]

    # repetition counts along the actual game
    rep_seen: dict[str, int] = {}
    rep_at: dict[int, int] = {}
    b = chess.Board(g["start_fen"])
    for mv in g["moves"]:
        key = " ".join(b.fen().split()[:4])
        rep_at[mv["ply"]] = rep_seen.get(key, 0)
        rep_seen[key] = rep_seen.get(key, 0) + 1
        b.push(chess.Move.from_uci(mv["uci"]))

    for r in rows:
        board = chess.Board(r["fen"])
        lines = r.get("sf_lines") or []
        if not lines:
            continue
        d = int(r.get("sf_depth") or depth)
        legal = [board.san(m) for m in board.legal_moves]
        played = chess.Move.from_uci(r["move"])
        out += [
            f'[GID "{game_id}"]', f'[EID "{engine}"]', f'[Turn "{r["move_no"]}-{r["color"][0]}"]',
            f'[MovePlayed "{board.san(played)}"]',
            f'[EngineMove "{board.san(chess.Move.from_uci(lines[0]["move"]))}"]',
            f'[Eval "{_cell(lines[0]["cp"])}"]', f'[Depth "{d}"]', '[NodeCount "n.a."]',
            f'[FEN "{r["fen"]}"]', f'[RepCount "{rep_at.get(r["ply"], 0)}"]',
            f'[NumLegalMoves "{len(legal)}"]', f'[LegalMoves "{_wrap(legal)}"]',
        ]
        if r.get("sf_quick"):
            out.append("; decided position: depth-8 single-PV prefilter only (ChessAssistLens eligibility rule)")
        if r.get("substituted"):
            out.append(f"; synthetic substitution: human played {r.get('san')}")
        sep = "-" * (5 + 5 * d)
        out += ["", sep, "    " + "".join(f"{k:>5d}" for k in range(1, d + 1)), sep]
        listed = set()
        for ln in lines:
            san = board.san(chess.Move.from_uci(ln["move"]))
            listed.add(ln["move"])
            out.append(f"{san:<5}" + " ".join(["n.a."] * (d - 1) + [_cell(ln["cp"])]))
        if r["move"] not in listed:
            out.append(f"{board.san(played):<5}" + " ".join(["PRUN"] * d))
        out += ["", f"{d}: " + _pv_san(r["fen"], lines[0].get("pv") or [lines[0]["move"]]), ""]
    return "\n".join(out) + "\n"
