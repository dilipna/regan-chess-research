"""Write docs/THREE_MODEL_RESULTS.md from the exported three-model result files (no number is typed by hand).

Reads data/artifacts/three_model_{move_prediction,assistance_results,bootstrap}.json, and metrics.json +
paired_bootstrap.json for the unchanged hybrid A/B/C/D reference values. Models whose status is
"pending" are listed as not yet run; nothing is filled in for them.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "services"))
from analyzer import config  # noqa: E402

A = config.ARTIFACTS
NAME = {"R": "Regan-inspired reconstruction", "Q": "Qwen3-8B-Base", "Q0": "Qwen3-8B-Base (position-only)",
        "M": "Maia-3 79M", "M5": "Maia-3 5M (secondary)"}
T1 = [("top1_accuracy", "Top-1 move accuracy", "pct", "higher"), ("top3_accuracy", "Top-3 move accuracy", "pct", "higher"),
      ("mean_nll", "Mean negative log-likelihood (nats)", "f3", "lower"), ("brier_multiclass", "Brier score (multi-class)", "f3", "lower"),
      ("mean_rank", "Mean rank of played move", "f2", "lower"), ("t1_event_logloss", "Engine-first-move event: log-loss", "f3", "lower"),
      ("t1_event_brier", "Engine-first-move event: Brier", "f3", "lower"), ("t3_event_logloss", "Engine-top-3 event: log-loss", "f3", "lower"),
      ("t3_event_brier", "Engine-top-3 event: Brier", "f3", "lower")]


def fmt(x, kind):
    if x is None:
        return "not defined"
    return f"{100 * x:.1f}%" if kind == "pct" else (f"{x:.3f}" if kind == "f3" else f"{x:.2f}")


def main():
    mp = json.loads((A / "three_model_move_prediction.json").read_text())
    ar = json.loads((A / "three_model_assistance_results.json").read_text())
    bs = json.loads((A / "three_model_bootstrap.json").read_text())
    met = json.loads((A / "metrics.json").read_text())
    ok1 = [k for k in ("R", "Q", "M", "M5") if mp["models"][k]["status"] == "ok"]
    ok2 = [k for k in ("R", "Q", "M", "M5") if ar["models"][k]["status"] == "ok"]
    pending = sorted({NAME[k] for k in ("Q", "Q0") if mp["models"][k]["status"] != "ok"})
    L = ["# Model comparison results (generated)", "",
         f"Generated by `experiments/19_three_model_results_md.py` from `{mp['generator']['script']}` output "
         f"({mp['generator']['generated_utc']}); analysis plan `{mp['generator']['plan_version']}`, "
         f"SHA-256 `{mp['generator']['plan_sha256'][:16]}…` (frozen before test evaluation).", ""]
    if pending:
        L += [f"**Not yet run:** {', '.join(pending)}. No values are reported for these; nothing is estimated in their place.", ""]
    L += ["The Regan-inspired reconstruction is a public reconstruction of Professor Regan's documented framework, not his "
          "analyzer. It outputs no probability for every legal move, so move-level metrics are *not defined* for it; it is "
          "compared on the engine-first-move and engine-top-3 events, which every model predicts.", "",
          "## Task 1 — predicting original (presumed-human) moves", "",
          f"{mp['data']['positions']:,} eligible decisions of {mp['data']['player_games']} original test player-games "
          f"({mp['data']['source_games']} source games). 95% intervals: source-game cluster bootstrap, "
          f"{bs['n_boot']} resamples.", "",
          "| Metric | " + " | ".join(NAME[k] for k in ok1) + " |", "|---|" + "---|" * len(ok1)]
    for key, label, kind, better in T1:
        cells = []
        for k in ok1:
            m = mp["models"][k]
            v = m["metrics"].get(key)
            ci = m.get("ci95", {}).get(key)
            cells.append(fmt(v, kind) + (f" [{fmt(ci[0], kind)}, {fmt(ci[1], kind)}]" if ci and v is not None else ""))
        L.append(f"| {label} ({better} is better) | " + " | ".join(cells) + " |")
    L += ["", "## Task 2 — response to controlled decision-level substitutions", "",
          f"{ar['data']['rows']:,} test rows ({ar['data']['positives']:,} with substitutions evaluated in the original positions). "
          "Score: z(top-1) for the reconstruction; mean surprisal of the evaluated moves for move-distribution models. "
          f"Low-FPR thresholds from {ar['data']['val_original_player_games_for_thresholds']} validation original player-games; "
          "realized test FPR in parentheses (different realized FPRs are not the same operating point).", "",
          "| Model | ROC-AUC [95% CI] | PR-AUC | Recall @1% target (FPR) | Recall @5% target (FPR) | Secondary: excess-surprisal AUC |",
          "|---|---|---|---|---|---|"]
    for k in ok2:
        m = ar["models"][k]
        t = m["tpr_at_fpr"]
        sec = m.get("secondary_excess_surprisal")
        L.append(f"| {NAME[k]} | {m['roc_auc']:.3f} [{m['roc_auc_ci95'][0]:.3f}, {m['roc_auc_ci95'][1]:.3f}] | {m['pr_auc']:.3f} | "
                 f"{100 * t[0]['tpr']:.1f}% ({100 * t[0]['test_fpr']:.1f}%) | {100 * t[1]['tpr']:.1f}% ({100 * t[1]['test_fpr']:.1f}%) | "
                 f"{f'{sec['roc_auc']:.3f}' if sec else '—'} |")
    L += ["", "## Paired differences (second − first)", "",
          "Same bootstrap resamples for both models; no refitting; no multiplicity correction.", "",
          "| Task | From → To | Metric | Difference [paired 95% CI] | Reading |", "|---|---|---|---|---|"]
    for c in bs["comparisons"]:
        if c["status"] != "ok":
            continue
        lo, hi = c["ci95"]
        if lo <= 0 <= hi:
            reading = "interval includes 0"
        else:
            b_higher = lo > 0
            better = c["to"] if (b_higher != c["lower_is_better"]) else c["from"]
            reading = f"favours {NAME[better]}"
        L.append(f"| {c['task']} | {NAME[c['from']]} → {NAME[c['to']]} | {c['metric']} | {c['delta']:+.4f} [{lo:+.4f}, {hi:+.4f}] | {reading} |")
    ex = met["experiments"]
    pairs = json.loads((A / "paired_bootstrap.json").read_text())
    pb = {(r["from"], r["to"]): r for r in pairs["comparisons"]}
    L += ["", "## Hybrid extension (validated, unchanged)", "",
          "| System | ROC-AUC | Recall @1% target (realized FPR) |", "|---|---|---|"]
    for k in ("A_stat", "B_sf", "C_sf_maia", "D_sf_maia_seq"):
        c = ex[k]["classifier"]
        t = c["tpr_at_fpr"][0]
        L.append(f"| {ex[k]['label']} | {c['roc_auc']:.3f} | {100 * t['tpr']:.1f}% ({100 * t['test_fpr']:.1f}%) |")
    L += ["", "Paired ROC-AUC differences: " + "; ".join(
        f"{a}→{b} {pb[(a, b)]['delta']:+.4f} [{pb[(a, b)]['ci95'][0]:+.4f}, {pb[(a, b)]['ci95'][1]:+.4f}]"
        for a, b in (("A_stat", "B_sf"), ("B_sf", "C_sf_maia"), ("C_sf_maia", "D_sf_maia_seq"))) + ".", "",
          "## Caveats", ""] + [f"* {c}" for c in mp["caveats"]] + [""]
    out = config.ROOT / "docs" / "THREE_MODEL_RESULTS.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    main()
